<?php

declare(strict_types=1);

namespace NyonCode\LaravelPwa\Manifest;

use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\File;
use InvalidArgumentException;
use NyonCode\LaravelPwa\Contracts\ManifestParameters;
use NyonCode\LaravelPwa\Contracts\ManifestResolver;

/**
 * Builds the web app manifest from the config, fluent calls and per-request resolvers.
 *
 * Fluent calls (e.g. in AppServiceProvider::boot) override the config. Resolvers run for every
 * manifest request on a copy of the builder (forRequest), so nothing leaks between requests.
 */
class ManifestBuilder
{
    /** @var array<string, mixed> */
    protected array $overrides = [];

    /** @var list<array<string, mixed>> */
    protected array $shortcuts = [];

    /** @var list<array<string, mixed>> */
    protected array $fileHandlers = [];

    /** @var list<array<string, string>> */
    protected array $protocolHandlers = [];

    /** @var list<string> */
    protected array $displayOverride = [];

    /** @var list<array<string, string>> */
    protected array $customIcons = [];

    /** @var list<array{0: ManifestResolver|Closure|class-string<ManifestResolver>, 1: Closure|null}> */
    protected array $resolvers = [];

    protected ?string $locale = null;

    protected bool $private = false;

    /** @var list<string> */
    protected array $vary = [];

    public function set(string $key, mixed $value): static
    {
        $this->overrides[$key] = $value;

        return $this;
    }

    public function name(string $name): static
    {
        return $this->set('name', $name);
    }

    public function shortName(string $shortName): static
    {
        return $this->set('short_name', $shortName);
    }

    public function description(string $description): static
    {
        return $this->set('description', $description);
    }

    /**
     * The app identity. Changing it makes browsers treat the app as a new one.
     */
    public function id(string $id): static
    {
        return $this->set('id', $id);
    }

    public function startUrl(string $url): static
    {
        return $this->set('start_url', $url);
    }

    public function scope(string $scope): static
    {
        return $this->set('scope', $scope);
    }

    public function themeColor(string $color): static
    {
        return $this->set('theme_color', $color);
    }

    public function backgroundColor(string $color): static
    {
        return $this->set('background_color', $color);
    }

    /**
     * Adds an icon. Once any icon is added, the files generated by pwa:icons are no longer listed.
     */
    public function icon(string $src, string $sizes, ?string $type = null, string $purpose = 'any'): static
    {
        $this->customIcons[] = array_filter([
            'src' => $src,
            'sizes' => $sizes,
            'type' => $type ?? $this->mimeFor($src),
            'purpose' => $purpose,
        ], static fn (?string $value): bool => $value !== null);

        return $this;
    }

    /**
     * Builds the manifest in this locale (name, short_name and description from
     * `pwa::manifest.*` translations, `lang`, `dir`).
     */
    public function locale(string $locale): static
    {
        $this->locale = $locale;

        return $this;
    }

    /**
     * Marks the manifest as user- or tenant-specific: `Cache-Control: private`.
     */
    public function private(bool $private = true): static
    {
        $this->private = $private;

        return $this;
    }

    /**
     * Request headers the manifest depends on (sent as `Vary`).
     */
    public function vary(string ...$headers): static
    {
        $this->vary = array_values(array_unique([...$this->vary, ...$headers]));

        return $this;
    }

    public function shortcut(string $name, string $url, ?string $icon = null, ?string $description = null): static
    {
        $this->shortcuts[] = array_filter([
            'name' => $name,
            'url' => $url,
            'description' => $description,
            'icons' => ! in_array($icon, [null, '', '0'], true) ? [['src' => $icon, 'sizes' => '96x96']] : null,
        ]);

        return $this;
    }

    /**
     * @param  list<string>  $accept  MIME types, e.g. ['image/*', 'application/pdf']
     */
    public function shareTarget(string $action, string $method = 'POST', array $accept = [], string $filesField = 'files'): static
    {
        $method = strtoupper($method);

        $target = [
            'action' => $action,
            'method' => $method,
            'params' => ['title' => 'title', 'text' => 'text', 'url' => 'url'],
        ];

        if ($method === 'POST') {
            $target['enctype'] = $accept === [] ? 'application/x-www-form-urlencoded' : 'multipart/form-data';
        }

        if ($accept !== []) {
            $target['params']['files'] = [['name' => $filesField, 'accept' => $accept]];
        }

        return $this->set('share_target', $target);
    }

    /**
     * @param  array<string, list<string>>  $accept  e.g. ['text/csv' => ['.csv']]
     */
    public function fileHandler(string $action, array $accept, ?string $name = null): static
    {
        $this->fileHandlers[] = array_filter(['action' => $action, 'accept' => $accept, 'name' => $name]);

        return $this;
    }

    public function protocolHandler(string $protocol, string $url): static
    {
        $this->protocolHandlers[] = ['protocol' => $protocol, 'url' => $url];

        return $this;
    }

    public function windowControlsOverlay(): static
    {
        return $this->prependDisplayOverride('window-controls-overlay');
    }

    /**
     * @param  array<string, mixed>  $tabStrip
     */
    public function tabbed(array $tabStrip = []): static
    {
        if ($tabStrip !== []) {
            $this->set('tab_strip', $tabStrip);
        }

        return $this->prependDisplayOverride('tabbed');
    }

    /**
     * @param  string|list<string>  $clientMode  navigate-existing | focus-existing | navigate-new | auto
     */
    public function launchHandler(string|array $clientMode): static
    {
        return $this->set('launch_handler', ['client_mode' => $clientMode]);
    }

    /**
     * Registers a per-request resolver: a ManifestResolver (instance or class name, resolved from
     * the container) or a closure `fn (Request $request, ManifestBuilder $manifest): void`.
     *
     * A closure gets its manifest link parameters from `$parameters`
     * (`fn (Request $page): array<string, string>`); a class implements ManifestParameters.
     *
     * @param  ManifestResolver|Closure|class-string<ManifestResolver>  $resolver
     */
    public function resolveUsing(ManifestResolver|Closure|string $resolver, ?Closure $parameters = null): static
    {
        $this->resolvers[] = [$resolver, $parameters];

        return $this;
    }

    /**
     * A copy of this builder with every resolver applied for the given manifest request.
     */
    public function forRequest(Request $request): static
    {
        $manifest = clone $this;
        $manifest->resolvers = [];

        foreach ($this->resolverPairs() as [$resolver]) {
            $resolver instanceof ManifestResolver
                ? $resolver->resolve($request, $manifest)
                : $resolver($request, $manifest);
        }

        return $manifest;
    }

    /**
     * Query parameters for the manifest link on the given page, collected from the resolvers.
     *
     * @return array<string, string>
     */
    public function parameters(Request $page): array
    {
        $parameters = [];

        foreach ($this->resolverPairs() as [$resolver, $closure]) {
            $values = match (true) {
                $resolver instanceof ManifestParameters => $resolver->parameters($page),
                $closure instanceof Closure => $closure($page),
                default => [],
            };

            if (! is_array($values)) {
                throw new InvalidArgumentException('Manifest parameters must be an array of strings.');
            }

            foreach ($values as $key => $value) {
                if (! is_string($key) || ! is_scalar($value)) {
                    throw new InvalidArgumentException('Manifest parameters must be an array of strings.');
                }

                $parameters[$key] = (string) $value;
            }
        }

        ksort($parameters);

        return $parameters;
    }

    /**
     * The manifest link for a page, with the resolvers' parameters.
     */
    public function url(Request $page): string
    {
        $parameters = $this->parameters($page);

        return route('pwa.manifest', absolute: false).($parameters === [] ? '' : '?'.http_build_query($parameters));
    }

    /**
     * @return array{public: bool, vary: list<string>}
     */
    public function cachePolicy(): array
    {
        return ['public' => ! $this->private, 'vary' => $this->vary];
    }

    /**
     * @return array<string, mixed>
     */
    public function toArray(?Request $request = null): array
    {
        $request ??= request();
        $locale = $this->locale ?? app()->getLocale();

        $name = $this->translated('name', $locale, config()->string('pwa.name', 'Laravel'));
        $shortName = $this->translated('short_name', $locale, $this->configString('pwa.short_name') ?? $name);

        $manifest = [
            'id' => config()->string('pwa.id', '/'),
            'name' => $name,
            'short_name' => $shortName,
            'description' => $this->translated('description', $locale, $this->configString('pwa.description') ?? ''),
            'lang' => str_replace('_', '-', $locale),
            'dir' => in_array(substr($locale, 0, 2), ['ar', 'he', 'fa', 'ur'], true) ? 'rtl' : 'ltr',
            'start_url' => config()->string('pwa.start_url', '/'),
            'scope' => config()->string('pwa.scope', '/'),
            ...DisplayStrategy::fromConfig()->resolve($request),
            'orientation' => config('pwa.orientation'),
            'theme_color' => config()->string('pwa.theme.light', '#ffffff'),
            'background_color' => config()->string('pwa.theme.background', '#ffffff'),
            'categories' => config('pwa.categories') ?: null,
            'icons' => $this->customIcons !== [] ? $this->customIcons : $this->icons(),
            'screenshots' => config('pwa.screenshots') ?: null,
            'shortcuts' => array_values([...(array) config('pwa.shortcuts', []), ...$this->shortcuts]) ?: null,
            'share_target' => config('pwa.share_target'),
            'file_handlers' => array_values([...(array) config('pwa.file_handlers', []), ...$this->fileHandlers]) ?: null,
            'protocol_handlers' => array_values([...(array) config('pwa.protocol_handlers', []), ...$this->protocolHandlers]) ?: null,
            'launch_handler' => config('pwa.launch_handler'),
            'scope_extensions' => config('pwa.scope_extensions') ?: null,
        ];

        if ($this->displayOverride !== []) {
            $manifest['display_override'] = array_values(array_unique([
                ...$this->displayOverride,
                ...(array) ($manifest['display_override'] ?? []),
            ]));
        }

        $manifest = [...$manifest, ...$this->localized(), ...$this->overrides];

        return array_filter($manifest, static fn (mixed $value): bool => ! in_array($value, [null, '', []], true));
    }

    public function toJson(?Request $request = null): string
    {
        return json_encode($this->toArray($request), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR);
    }

    /**
     * Icons in public/{icons.path} generated by pwa:icons. Only files that exist.
     *
     * @return list<array<string, string>>
     */
    public function icons(): array
    {
        $path = trim(config()->string('pwa.icons.path', 'pwa/icons'), '/');
        $icons = [];

        foreach (config()->array('pwa.icons.sizes', [192, 512]) as $size) {
            $size = is_numeric($size) ? (int) $size : 0;
            $file = "icon-{$size}.png";

            if ($size > 0 && File::exists(public_path("{$path}/{$file}"))) {
                $icons[] = ['src' => "/{$path}/{$file}", 'sizes' => "{$size}x{$size}", 'type' => 'image/png', 'purpose' => 'any'];
            }
        }

        if (File::exists(public_path("{$path}/maskable-512.png"))) {
            $icons[] = ['src' => "/{$path}/maskable-512.png", 'sizes' => '512x512', 'type' => 'image/png', 'purpose' => 'maskable'];
        }

        if (File::exists(public_path("{$path}/icon.svg"))) {
            $icons[] = ['src' => "/{$path}/icon.svg", 'sizes' => 'any', 'type' => 'image/svg+xml', 'purpose' => 'any'];
        }

        return $icons;
    }

    /**
     * For tests and Octane: drops fluent settings and resolvers.
     */
    public function flush(): void
    {
        $this->overrides = $this->shortcuts = $this->fileHandlers = $this->protocolHandlers = $this->displayOverride = $this->customIcons = $this->resolvers = $this->vary = [];
        $this->locale = null;
        $this->private = false;
    }

    /**
     * @return array<string, mixed>
     */
    public function overrides(): array
    {
        return [
            'overrides' => $this->overrides,
            'shortcuts' => $this->shortcuts,
            'fileHandlers' => $this->fileHandlers,
            'protocolHandlers' => $this->protocolHandlers,
            'displayOverride' => $this->displayOverride,
            'customIcons' => $this->customIcons,
        ];
    }

    /**
     * Resolvers in order: locale (when pwa.locales is set), `pwa.manifest.resolvers`, fluent ones.
     *
     * @return list<array{0: ManifestResolver|Closure, 1: Closure|null}>
     */
    protected function resolverPairs(): array
    {
        $pairs = [];

        if (config()->array('pwa.locales', []) !== []) {
            $pairs[] = [app(LocaleResolver::class), null];
        }

        foreach ([...array_map(static fn (mixed $class): array => [$class, null], config()->array('pwa.manifest.resolvers', [])), ...$this->resolvers] as [$resolver, $parameters]) {
            if (is_string($resolver)) {
                $resolver = app($resolver);
            }

            if (! $resolver instanceof ManifestResolver && ! $resolver instanceof Closure) {
                throw new InvalidArgumentException('A manifest resolver must implement '.ManifestResolver::class.' or be a closure, '.get_debug_type($resolver).' given.');
            }

            $pairs[] = [$resolver, $parameters];
        }

        return $pairs;
    }

    /**
     * Localised variants of name / short_name / description (Chromium 147+).
     *
     * @return array<string, array<string, string>>
     */
    protected function localized(): array
    {
        $locales = array_values(array_filter(config()->array('pwa.locales', []), is_string(...)));

        if ($locales === []) {
            return [];
        }

        $result = [];

        foreach (['name', 'short_name', 'description'] as $member) {
            foreach ($locales as $locale) {
                $key = "pwa::manifest.{$member}";
                // Without the fallback locale: a missing translation must not be labelled as this locale.
                $value = app('translator')->get($key, [], $locale, false);

                if (is_string($value) && $value !== $key && $value !== '') {
                    $result["{$member}_localized"][str_replace('_', '-', $locale)] = $value;
                }
            }
        }

        return $result;
    }

    protected function translated(string $member, string $locale, string $fallback): string
    {
        $key = "pwa::manifest.{$member}";
        $value = app('translator')->get($key, [], $locale);

        return is_string($value) && $value !== $key && $value !== '' ? $value : $fallback;
    }

    protected function configString(string $key): ?string
    {
        $value = config($key);

        return is_string($value) && $value !== '' ? $value : null;
    }

    protected function mimeFor(string $src): ?string
    {
        return match (strtolower(pathinfo((string) parse_url($src, PHP_URL_PATH), PATHINFO_EXTENSION))) {
            'png' => 'image/png',
            'svg' => 'image/svg+xml',
            'webp' => 'image/webp',
            'jpg', 'jpeg' => 'image/jpeg',
            'ico' => 'image/x-icon',
            default => null,
        };
    }

    protected function prependDisplayOverride(string $mode): static
    {
        $this->displayOverride = array_values(array_unique([$mode, ...$this->displayOverride]));

        return $this;
    }
}
